import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read = path => readFileSync(new URL('../'+path,import.meta.url),'utf8');
const src = read('src/commerce-prices.js');
const css = read('assets/site.css');
const shared = read('src/shared.js');
const metadata = JSON.parse(read('package.json'));
assert.ok(src.includes('onstore.c2.1.currency-picker.flags.dropdown'),'New currency selector implementation');
assert.ok(!src.includes("document.createElement('select')"),'Native mobile select replaced by anchored menu');
assert.ok(src.includes("'🇺🇸'") && src.includes("'🇰🇪'") && src.includes("'🇬🇧'"),'Three flag symbols');
assert.ok(src.includes("aria-haspopup', 'menu'") && src.includes("role', 'menuitemradio'"),'Accessible menu semantics');
assert.ok(src.includes("onstore:currency-changed") && src.includes('refreshVisiblePrices()'),'Existing site-wide price refresh preserved');
assert.ok(src.includes("document.activeElement?.blur()"),'Touch focus cleared on selection');
assert.ok(css.includes('.commerce-currency-menu[hidden]'),'Menu closes completely');
assert.ok(css.includes('top: calc(100% + 8px)') && css.includes('position: absolute'),'Menu anchored below button');
assert.ok(css.includes('.commerce-currency-trigger:focus-visible'),'Keyboard focus still visible');
assert.ok(shared.includes('createCurrencyPicker()'),'Shared header still uses currency picker');
assert.ok(metadata.scripts.test.includes('validate-currency-pricing.mjs'),'Previous currency test preserved');
console.log('PASS: C2.1 compact flag picker, dropdown under selector, touch-focus cleanup, currency refresh and keyboard access');
