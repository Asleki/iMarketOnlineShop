import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {convertedMinor,formattedMoney,supportedCurrencies} from '../src/commerce-prices.js';
const read = p => JSON.parse(readFileSync(new URL('../'+p,import.meta.url),'utf8'));
const prices=read('data/commerce/base-prices.json');
const publicPrices=read('data/commerce/public-prices.json');
const rates=read('data/commerce/exchange-rates.json');
const c1=read('data/commerce/sku-registry.json');
const all=read('api/v1/catalogue.json').products;
assert.equal(prices.schema,'onstore.base-prices.v1');
assert.equal(publicPrices.schema,'onstore.public-prices.v1');
assert.equal(prices.entry_count,prices.entries.length);
assert.equal(publicPrices.price_count,publicPrices.entries.length);
assert.equal(prices.entries.length,210,'210 initial USD price records');
assert.deepEqual(supportedCurrencies,['USD','KES','GBP']);
assert.deepEqual(Object.keys(rates.rates_scaled).sort(),['GBP','KES','USD']);
assert.equal(rates.rates_scaled.USD,1_000_000);
assert.ok(rates.rates_scaled.KES>0 && rates.rates_scaled.GBP>0);
assert.equal(new Set(prices.entries.map(x=>x.sku)).size,prices.entries.length);
const indexed=new Map(c1.items.map(x=>[x.sku,x]));
const cat=new Map(all.map(p=>[p.shop_slug+'|'+p.id,p]));
let scenarios=0;
for(const row of prices.entries){
 const reg=indexed.get(row.sku);
 assert.ok(reg,'Unknown SKU '+row.sku);
 assert.equal(reg.shop_slug,row.shop_slug);
 assert.equal(reg.canonical_id,row.canonical_id);
 assert.ok(cat.has(row.shop_slug+'|'+row.canonical_id));
 assert.ok(Number.isSafeInteger(row.usd_cents) && row.usd_cents>0);
 if(row.price_mode==='design_scenario')scenarios++;
 const pub=publicPrices.entries.find(p=>p.sku===row.sku);
 assert.equal(pub.usd_cents,row.usd_cents);
}
assert.equal(scenarios,30,'Location-neutral property references stay scenario-only');
assert.equal(convertedMinor(10000,129732000),1297320,'100 USD becomes 12,973.20 KES using initial reference rate');
assert.equal(convertedMinor(10000,749586),7496,'100 USD becomes 74.96 GBP');
assert.match(formattedMoney(10999,'GBP'),/109\.99/);
const shared=readFileSync(new URL('../src/shared.js',import.meta.url),'utf8');
const catalogue=readFileSync(new URL('../src/catalogue-ui.js',import.meta.url),'utf8');
assert.ok(shared.includes('createCurrencyPicker()'),'Shared header currency picker');
assert.ok(catalogue.includes('createPriceNode(p)'),'Catalogue cards show converted prices');
assert.ok(catalogue.includes('createPriceNode(p)'),'Prices on cards');
console.log('PASS: C2 210 individualized USD seeds, USD/KES/GBP conversion, shop SKU ownership, property design-price safeguards, shared price picker');
