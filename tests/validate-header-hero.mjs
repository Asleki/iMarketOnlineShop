// Stage 3 hero v2: icon-only actions, dynamic image-qualified selection, 7 s full-bleed hero.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { selectHeroSlides } from '../src/hero.js';
const read = p => readFileSync(new URL('../' + p, import.meta.url), 'utf8');
const index = read('index.html');
const shared = read('src/shared.js');
const hero = read('src/hero.js');
const catalogue = read('src/catalogue-ui.js');
const main = read('src/app.js');
const css = read('assets/site.css');
const products = JSON.parse(read('api/v1/catalogue.json')).products;
assert.ok(index.includes('id="featured"') && index.includes('id="hero-slider"'));
assert.equal((index.match(/rel="stylesheet"/g)||[]).length,1);
assert.equal((index.match(/<script\b/g)||[]).length,1);
assert.ok(shared.includes('onstore-mark.svg') && !shared.includes('brand-wordmark'), 'Single bag image only');
assert.ok(shared.includes("element('summary', 'commerce-icon-action')"));
assert.ok(shared.includes("element('button', 'commerce-icon-action commerce-cart')"));
assert.ok(shared.includes("'Sign In'") && shared.includes("'Register'"));
assert.ok(shared.includes('Hello, Guest') && shared.includes('bindThemeToggle'));
assert.ok(css.includes('.commerce-icon-action[data-tooltip]') && css.includes('onstore.stage3.hero.dynamic.7s.v2'));
assert.ok(hero.includes('ROTATE_MS = 7000') && hero.includes('setInterval'), 'Hero rotates every 7 seconds');
assert.ok(hero.includes('onstore:open-product') && catalogue.includes('onstore:open-product'));
assert.ok(hero.includes('prefers-reduced-motion') && hero.includes('Previous featured product'));
assert.ok(hero.includes('object-fit') === false && css.includes('object-fit: cover'), 'Full-bleed hero uses CSS cover');
assert.ok(hero.includes('selectHeroSlides(data.products)'), 'Selection is catalogue-driven');
assert.ok(!hero.includes('const SELECTED ='), 'No fixed featured product names');
assert.ok(!hero.includes('Catalogue preview · Pricing and availability not confirmed'));
assert.ok(!index.includes('Discover seven shops · Explore 210 catalogue designs and products · No unverified price claims'));
assert.ok(!index.includes('hero-marquee'), 'Do not show an unapproved advertising message');
assert.ok(main.includes('initHero()'));
const qualified = products.filter(p => p.main_image && p.media.some(m => m.path === p.main_image));
assert.equal(qualified.length, 180, 'All 180 eligible illustrated products qualify');
assert.equal(new Set(qualified.map(p => p.shop_slug)).size, 6);
const selection = selectHeroSlides(products, 5, [], () => .42);
assert.equal(selection.length, 5);
assert.equal(new Set(selection.map(p => p.shop_slug)).size, 5, 'Diverse shop selection');
assert.ok(selection.every(p => qualified.includes(p)), 'Only verified-image records may feature');
const nextRound = selectHeroSlides(products, 5, selection, () => .28);
assert.equal(nextRound.length, 5);
assert.ok(nextRound.every(p => !selection.includes(p)), 'New round avoids immediately repeated products');
console.log('PASS: icon-only header preserved; dynamic 7-second, 100%-cover hero; 180 eligible images; no hardcoded products or unwanted notices');
